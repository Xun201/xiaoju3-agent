def sanitize_for_web(text):
    """Web 通道净化：face 码→Emoji、image 码→[表情]、其余 CQ 码剥除。

    纯函数无副作用，按 face → image → 其余 的固定次序处理（先精确后兜底，
    防止通用规则吞掉表情码）；非字符串入参先安全转 str，调用点无需判型。
    """
    if not isinstance(text, str):
        text = "" if text is None else str(text)

    def _face(match):
        return CQ_FACE_EMOJI.get(match.group(1), FACE_FALLBACK)

    text = FACE_RE.sub(_face, text)               # ① 表情码 → Emoji（未收录兜底）
    text = IMAGE_RE.sub(IMAGE_PLACEHOLDER, text)  # ② 图片码 → [表情] 占位（不泄露本机路径）
    text = OTHER_CQ_RE.sub('', text)              # ③ 其余 CQ 码（at/record 等）剥除
    return text.strip()
