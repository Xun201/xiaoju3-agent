IMAGE_RE = re.compile(r'\[CQ:image,[^\]]*\]')
OTHER_CQ_RE = re.compile(r'\[CQ:[^\]]*\]')

# 未收录 face id 的兜底表情（通用微笑），保证不留方括号原文
